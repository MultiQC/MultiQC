import logging
from collections import defaultdict
from typing import Dict

from multiqc.base_module import BaseMultiqcModule, ModuleNoSamplesFound
from multiqc.plots import bargraph, scatter
from multiqc.plots.bargraph import BarPlotConfig

log = logging.getLogger(__name__)


class MultiqcModule(BaseMultiqcModule):
    """
    The `dnaapler` module parses the per-contig reorientation summary tables
    (`*_all_reorientation_summary.tsv`) generated by `dnaapler all` and `dnaapler bulk`.

    Sample names are parsed from the summary filename by stripping the
    `_all_reorientation_summary.tsv` suffix (matching the `--prefix` argument passed
    to `dnaapler`).

    Versions 1.3.0 and 1.4.0 of `dnaapler` have been tested.
    """

    def __init__(self) -> None:
        super().__init__(
            name="dnaapler",
            anchor="dnaapler",
            href="https://github.com/gbouras13/dnaapler",
            info="Reorients complete circular microbial genomes to begin at a conserved start gene.",
            doi="10.21105/joss.05968",
            license="MIT License",
            license_url="https://opensource.org/license/mit",
        )

        parsed_data: Dict[str, Dict[str, int]] = {}
        scatter_data: Dict[str, List[Dict[str, Any]]] = defaultdict(list)

        for f in self.find_log_files("dnaapler"):
            s_name = self.clean_s_name(
                f["fn"].removesuffix("_all_reorientation_summary.tsv"), f
            )
            if s_name in parsed_data:
                log.debug(f"Duplicate sample name found! Overwriting: {s_name}")

            sample_counts: Dict[str, int] = defaultdict(int)
            sample_scatter: Dict[str, List[Dict[str, Any]]] = defaultdict(list)

            lines = f["f"].splitlines()
            for line in lines[1:]:
                if not line.strip():
                    continue
                cols = line.split("\t")
                if len(cols) < 11:
                    continue

                contig_id = cols[0].split()[0]
                gene = cols[1].strip()
                sample_counts[gene] += 1

                if gene not in ("Contig_ignored", "No_MMseqs2_hits"):
                    try:
                        coverage = float(cols[7])
                        identity = float(cols[9])
                        sample_scatter[gene].append(
                            {
                                "x": identity,
                                "y": coverage,
                                "name": f"{s_name}: {contig_id} ({gene})",
                            }
                        )
                    except ValueError:
                        log.debug(
                            f"Could not parse alignment metrics for {s_name} ({contig_id})"
                        )

            if sample_counts:
                parsed_data[s_name] = dict(sample_counts)
                for gene, points in sample_scatter.items():
                    scatter_data[gene].extend(points)
                self.add_data_source(f, s_name=s_name)

        # Superfluous function call to confirm that it is used in this module
        # Replace None with actual version if it is available
        self.add_software_version(None)

        parsed_data = self.ignore_samples(parsed_data)
        if len(parsed_data) == 0:
            raise ModuleNoSamplesFound
        log.info(f"Found {len(parsed_data)} reports")

        valid_samples = set(parsed_data.keys())
        for gene in list(scatter_data.keys()):
            scatter_data[gene] = [
                pt
                for pt in scatter_data[gene]
                if pt["name"].split(": ")[0] in valid_samples
            ]

        summary_data: Dict[str, Dict[str, Union[int, float]]] = {}
        for s_name, counts in parsed_data.items():
            total = sum(counts.values())
            unreoriented = counts.get("Contig_ignored", 0) + counts.get(
                "No_MMseqs2_hits", 0
            )
            reoriented = total - unreoriented
            summary_data[s_name] = {
                "reoriented_contigs": reoriented,
                "pct_reoriented": (reoriented / total * 100.0) if total > 0 else 0.0,
                **counts,
            }

        self.add_general_stats(summary_data)
        self.add_reorientation_barplot(parsed_data)
        if any(scatter_data.values()):
            self.add_alignment_scatter(scatter_data)

        self.write_data_file(summary_data, "multiqc_dnaapler")

    def add_general_stats(
        self, summary_data: Dict[str, Dict[str, Union[int, float]]]
    ) -> None:
        headers: Dict[str, Dict[str, Any]] = {
            "reoriented_contigs": {
                "title": "Reoriented",
                "description": "Number of contigs reoriented by dnaapler",
                "min": 0,
                "scale": "Blues",
                "format": "{:,.0f}",
            },
            "pct_reoriented": {
                "title": "% Reoriented",
                "description": "Percentage of contigs in the summary table reoriented by dnaapler",
                "min": 0,
                "max": 100,
                "suffix": "%",
                "scale": "PuBu",
                "format": "{:,.1f}",
                "hidden": True,
            },
        }
        self.general_stats_addcols(summary_data, headers)

    def add_reorientation_barplot(
        self, parsed_data: Dict[str, Dict[str, int]]
    ) -> None:
        known_cats: Dict[str, Dict[str, str]] = {
            "dnaA": {"name": "dnaA (chromosome)", "color": "#1f78b4"},
            "repA": {"name": "repA (plasmid)", "color": "#33a02c"},
            "terL": {"name": "terL (phage)", "color": "#6a3d9a"},
            "COG1474": {"name": "COG1474 (archaea)", "color": "#ff7f00"},
            "largest_CDS": {"name": "Largest CDS (autocomplete)", "color": "#a6cee3"},
            "nearest_CDS": {"name": "Nearest CDS (autocomplete)", "color": "#b2df8a"},
            "random_CDS": {"name": "Random CDS (autocomplete)", "color": "#cab2d6"},
            "No_MMseqs2_hits": {"name": "No MMseqs2 hits", "color": "#e31a1c"},
            "Contig_ignored": {"name": "Contig ignored", "color": "#bdbdbd"},
        }

        all_keys = {k for counts in parsed_data.values() for k in counts}
        cats: Dict[str, Dict[str, str]] = {
            k: v for k, v in known_cats.items() if k in all_keys
        }
        for k in sorted(all_keys - set(known_cats.keys())):
            cats[k] = {"name": k}

        pconfig = BarPlotConfig(
            id="dnaapler_reorientation_summary",
            title="dnaapler: Contig Reorientation Summary",
            ylab="Number of Contigs",
        )
        self.add_section(
            name="Contig Reorientation",
            anchor="dnaapler-reorientation",
            description="Breakdown of contigs reoriented by start gene or skipped during processing.",
            plot=bargraph.plot(parsed_data, cats, pconfig=pconfig),
        )

    def add_alignment_scatter(
        self, scatter_data: Dict[str, List[Dict[str, Any]]]
    ) -> None:
        pconfig: Dict[str, Any] = {
            "id": "dnaapler_alignment_quality",
            "title": "dnaapler: Start-Gene Hit Alignment Quality",
            "xlab": "Identity (%)",
            "ylab": "Coverage (%)",
            "xmin": 0,
            "xmax": 100,
            "ymin": 0,
            "ymax": 100,
        }
        self.add_section(
            name="Start-Gene Alignment Quality",
            anchor="dnaapler-alignment-quality",
            description="MMseqs2 sequence identity and query coverage for reoriented contigs.",
            plot=scatter.plot(scatter_data, pconfig=pconfig),
        )
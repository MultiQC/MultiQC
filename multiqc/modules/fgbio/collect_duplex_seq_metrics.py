import logging

from multiqc import BaseMultiqcModule
from multiqc.plots import linegraph

log = logging.getLogger(__name__)


def collect_duplex_seq_metrics(module: BaseMultiqcModule) -> int:
    """
    Parse output from fgbio CollectDuplexSeqMetrics.

    Generates:
    - Duplex Yield Metrics plot (read_pairs vs duplexes)
    - Duplex Family Size Distribution plot
    - Simplex Family Size Distribution plot
    - Data export files for family sizes and duplex yield metrics
    """
    yield_data, yield_data_normed = parse_duplex_yield_metrics(module)
    duplex_sizes, duplex_sizes_normed, simplex_sizes, simplex_sizes_normed = parse_family_sizes(module)

    samples_parsed = set(yield_data.keys()) | set(duplex_sizes.keys()) | set(simplex_sizes.keys())

    if not samples_parsed:
        return 0

    # 1. Duplex Yield Metrics plot
    if yield_data:
        config = {
            "id": "fgbio-collectduplexseqmetrics-yield-plot",
            "title": "fgbio: Duplex Yield Metrics",
            "ylab": "Duplex Families (ds_duplexes)",
            "xlab": "Read Pairs",
            "data_labels": [
                {
                    "name": "Duplex Families",
                    "ylab": "Duplex Families (ds_duplexes)",
                    "xlab": "Read Pairs",
                },
                {
                    "name": "Duplex Percentage",
                    "ylab": "Duplex Percentage",
                    "xlab": "Read Pairs",
                    "ysuffix": "%",
                },
            ],
        }
        module.add_section(
            name="Duplex Yield Metrics",
            anchor="fgbio-collectduplexseqmetrics-yield",
            description=(
                "Duplex yield across downsampling fractions and read pairs, generated by `CollectDuplexSeqMetrics`."
            ),
            helptext="""
            This metric is generated by randomly downsampling the dataset at various
            coverage levels to estimate library complexity and project duplex yield as
            sequencing depth increases.
            """,
            plot=linegraph.plot([yield_data, yield_data_normed], config),
        )

    # 2. Duplex Family Size Distribution plot
    if duplex_sizes:
        config = {
            "id": "fgbio-collectduplexseqmetrics-duplex-family-size-plot",
            "title": "fgbio: Duplex Family Size Distribution",
            "ylab": "Number of Duplex Families",
            "xlab": "Family Size (Reads supporting family)",
            "xmax": 20,
            "data_labels": [
                {
                    "name": "Counts",
                    "ylab": "Number of Duplex Families",
                },
                {
                    "name": "Percentages",
                    "ylab": "Percentage of Duplex Families",
                    "ysuffix": "%",
                },
            ],
        }
        module.add_section(
            name="Duplex Family Size Distribution",
            anchor="fgbio-collectduplexseqmetrics-duplex-family-size",
            description=(
                "Distribution of double-stranded (duplex) tag family sizes, "
                "showing the number of families supported by a given number of reads."
            ),
            helptext="""
            Double-stranded (DS) tag families are collapsed across single-stranded families
            originating from the same double-stranded source molecule.
            """,
            plot=linegraph.plot([duplex_sizes, duplex_sizes_normed], config),
        )

    # 3. Simplex Family Size Distribution plot
    if simplex_sizes:
        config = {
            "id": "fgbio-collectduplexseqmetrics-simplex-family-size-plot",
            "title": "fgbio: Simplex Family Size Distribution",
            "ylab": "Number of Simplex Families",
            "xlab": "Family Size (Reads supporting family)",
            "xmax": 20,
            "data_labels": [
                {
                    "name": "Counts",
                    "ylab": "Number of Simplex Families",
                },
                {
                    "name": "Percentages",
                    "ylab": "Percentage of Simplex Families",
                    "ysuffix": "%",
                },
            ],
        }
        module.add_section(
            name="Simplex Family Size Distribution",
            anchor="fgbio-collectduplexseqmetrics-simplex-family-size",
            description=(
                "Distribution of single-stranded (simplex) tag family sizes, "
                "showing the number of families supported by a given number of reads."
            ),
            helptext="""
            Single-stranded (SS) tag families are defined by matching genomic coordinates,
            strand, and UMI.
            """,
            plot=linegraph.plot([simplex_sizes, simplex_sizes_normed], config),
        )

    return len(samples_parsed)


def parse_duplex_yield_metrics(module: BaseMultiqcModule) -> tuple[dict, dict]:
    yield_data: dict = {}
    yield_data_normed: dict = {}
    raw_yield_data: dict = {}

    for f in module.find_log_files("fgbio/duplex_yield_metrics", filehandles=True):
        module.add_data_source(f, section="Duplex Yield Metrics")
        s_name = f["s_name"]

        fh = f["f"]
        header = fh.readline().rstrip("\r\n").split("\t")
        if "read_pairs" not in header or "ds_duplexes" not in header:
            continue

        read_pairs_idx = header.index("read_pairs")
        ds_duplexes_idx = header.index("ds_duplexes")
        ds_fraction_idx = header.index("ds_fraction_duplexes") if "ds_fraction_duplexes" in header else None

        sample_yield = {}
        sample_yield_normed = {}
        sample_raw = {}

        for line in fh:
            parts = line.rstrip("\r\n").split("\t")
            if len(parts) != len(header):
                continue
            try:
                rp = int(parts[read_pairs_idx])
                duplexes = int(parts[ds_duplexes_idx])
                sample_yield[rp] = duplexes
                if ds_fraction_idx is not None:
                    sample_yield_normed[rp] = float(parts[ds_fraction_idx]) * 100.0
                sample_raw[rp] = dict(zip(header, parts))
            except ValueError:
                continue

        if sample_yield:
            yield_data[s_name] = sample_yield
            if sample_yield_normed:
                yield_data_normed[s_name] = sample_yield_normed
            raw_yield_data[s_name] = sample_raw

        module.add_software_version(None, s_name)

    yield_data = module.ignore_samples(yield_data)
    yield_data_normed = module.ignore_samples(yield_data_normed)
    raw_yield_data = module.ignore_samples(raw_yield_data)

    if raw_yield_data:
        module.write_data_file(raw_yield_data, "multiqc_fgbio_CollectDuplexSeqMetrics_duplex_yield_metrics")

    return yield_data, yield_data_normed


def parse_family_sizes(module: BaseMultiqcModule) -> tuple[dict, dict, dict, dict]:
    duplex_sizes: dict = {}
    duplex_sizes_normed: dict = {}
    simplex_sizes: dict = {}
    simplex_sizes_normed: dict = {}
    raw_family_sizes: dict = {}

    for f in module.find_log_files("fgbio/family_sizes", filehandles=True):
        module.add_data_source(f, section="Family Sizes")
        s_name = f["s_name"]

        fh = f["f"]
        header = fh.readline().rstrip("\r\n").split("\t")
        if "family_size" not in header:
            continue

        idx = {col: header.index(col) for col in header}
        sample_ds = {}
        sample_ds_norm = {}
        sample_ss = {}
        sample_ss_norm = {}
        sample_raw = {}

        for line in fh:
            parts = line.rstrip("\r\n").split("\t")
            if len(parts) != len(header):
                continue
            try:
                size = int(parts[idx["family_size"]])
                if "ds_count" in idx:
                    sample_ds[size] = int(parts[idx["ds_count"]])
                if "ds_fraction" in idx:
                    sample_ds_norm[size] = float(parts[idx["ds_fraction"]]) * 100.0
                if "ss_count" in idx:
                    sample_ss[size] = int(parts[idx["ss_count"]])
                if "ss_fraction" in idx:
                    sample_ss_norm[size] = float(parts[idx["ss_fraction"]]) * 100.0
                sample_raw[size] = dict(zip(header, parts))
            except ValueError:
                continue

        if sample_ds:
            duplex_sizes[s_name] = sample_ds
        if sample_ds_norm:
            duplex_sizes_normed[s_name] = sample_ds_norm
        if sample_ss:
            simplex_sizes[s_name] = sample_ss
        if sample_ss_norm:
            simplex_sizes_normed[s_name] = sample_ss_norm
        if sample_raw:
            raw_family_sizes[s_name] = sample_raw

        module.add_software_version(None, s_name)

    duplex_sizes = module.ignore_samples(duplex_sizes)
    duplex_sizes_normed = module.ignore_samples(duplex_sizes_normed)
    simplex_sizes = module.ignore_samples(simplex_sizes)
    simplex_sizes_normed = module.ignore_samples(simplex_sizes_normed)
    raw_family_sizes = module.ignore_samples(raw_family_sizes)

    if raw_family_sizes:
        module.write_data_file(raw_family_sizes, "multiqc_fgbio_CollectDuplexSeqMetrics_family_sizes")

    return duplex_sizes, duplex_sizes_normed, simplex_sizes, simplex_sizes_normed

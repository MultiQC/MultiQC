import logging
import math
from typing import Any

import yaml

from multiqc.base_module import BaseMultiqcModule, ModuleNoSamplesFound
from multiqc.plots import linegraph
from multiqc.plots.linegraph import LinePlotConfig

log = logging.getLogger(__name__)


def _make_alert(message: str, level: str = "info") -> str:
    """Create an HTML alert div for empty state messages."""
    return f'<div class="alert alert-{level}"><strong>{message}</strong></div>'


class MultiqcModule(BaseMultiqcModule):
    """
    Methurator is a Python package designed to estimate CpG saturation
    for DNA methylation sequencing data.

    The module parses the `methurator_summary.yml` file generated by the
    `methurator gt_estimator` command, which requires methurator >= 2.1.0.
    The file contains:

    - **GT summary**: The gt_estimator command performs Good-Toulmin extrapolation
      to estimate sequencing saturation and predict the theoretical maximum number
      of CpGs at higher depth.

    Summary files produced by the older `methurator downsample` command are not
    supported and are skipped with a warning.

    The module displays key metrics in the General Statistics table and creates a
    saturation curve plot showing how CpG saturation changes with sequencing depth.
    """

    def __init__(self):
        super().__init__(
            name="Methurator",
            anchor="methurator",
            href="https://github.com/VIBTOBIlab/methurator",
            info="Estimates CpG saturation for DNA methylation sequencing data.",
            # doi="",  # No DOI available
            license="MIT License",
            license_url="https://github.com/VIBTOBIlab/methurator/blob/main/LICENSE",
        )

        # Store parsed data
        self.methurator_data: dict[str, dict[str, Any]] = {}

        # Find and parse methurator summary files
        for f in self.find_log_files("methurator"):
            try:
                parsed = yaml.load(f["f"], Loader=yaml.SafeLoader)
                metadata = parsed["methurator_summary"]["metadata"]
                command = metadata["command"]
                version = str(metadata["methurator_version"])
            except (yaml.YAMLError, KeyError, TypeError) as e:
                log.warning(f"Could not parse methurator YAML file '{f['fn']}': {e!r}")
                continue

            # Only the gt_estimator command is supported
            if command != "methurator gt_estimator":
                log.warning(
                    f"Skipping '{f['fn']}': this module only supports output from the "
                    "`methurator gt_estimator` command (methurator >= 2.1.0), "
                    f"found command: {command!r}"
                )
                continue

            # Extract sample data from the parsed YAML
            samples_data = self._extract_sample_data(parsed, f["fn"])
            if not samples_data:
                log.warning(f"No sample data found in {f['fn']}")
                continue

            for sample_name, sample_data in samples_data.items():
                s_name = self.clean_s_name(sample_name, f)
                if s_name in self.methurator_data:
                    log.debug(f"Duplicate sample name found! Overwriting: {s_name}")
                self.methurator_data[s_name] = sample_data
                self.add_data_source(f, s_name=s_name)

                # Add software version if available
                self.add_software_version(version, s_name)

        # Filter ignored samples
        self.methurator_data = self.ignore_samples(self.methurator_data)

        # Raise exception if no data found
        if not self.methurator_data:
            raise ModuleNoSamplesFound

        log.info(f"Found {len(self.methurator_data)} samples")

        # Add general stats
        self._add_general_stats()

        # Add saturation curve plot (CpGs vs extrapolation factor)
        self._add_saturation_plot()

        # Write data file (must be last)
        self.write_data_file(self.methurator_data, "methurator")

    def _extract_sample_data(self, parsed: dict, fn: str) -> dict[str, dict[str, Any]]:
        """Extract per-sample data from the parsed `gt_estimator` YAML structure."""
        samples_data: dict[str, dict[str, Any]] = {}
        # Parse gt summary
        gt_summary = parsed["methurator_summary"]["gt_summary"]

        saturation_by_sample: dict[str, dict[int, dict[str, Any]]] = {}
        for item in gt_summary:
            for sample_name, sat_data in item.items():
                saturation_by_sample[sample_name] = {sat_entry["minimum_coverage"]: sat_entry for sat_entry in sat_data}
        # Combine all data for each sample
        all_samples = set(saturation_by_sample.keys())

        for sample_name in all_samples:
            sample_data: dict[str, Any] = {
                "saturation_analysis": saturation_by_sample[sample_name],
            }

            # Extract key metrics for general stats from the lowest minimum coverage
            # Get total CpGs at t = 1
            min_cov = min(sample_data["saturation_analysis"])
            predictions = sample_data["saturation_analysis"][min_cov]
            sample_data["minimum_coverage"] = min_cov
            sample_data["total_reads"] = predictions["reads"]
            sample_data["asymptote"] = predictions["asymptote(1000t)"]
            for prediction in predictions["data"]:
                # The t grid comes from np.arange, so some t_step values never hit t = 1 exactly
                if math.isclose(prediction[0], 1.0):
                    # prediction -> [t, saturation, CpGs, CI lower, CI higher]
                    sample_data["total_cpgs"] = prediction[2]
                    sample_data["saturation_pct"] = prediction[1] * 100
                    break
            else:
                log.warning(f"'{fn}': no t = 1 row for sample '{sample_name}', so CpGs and saturation are not reported")
            samples_data[sample_name] = sample_data
        return samples_data

    def _add_general_stats(self):
        """Add columns to the general statistics table."""
        general_stats_data: dict[str, dict[str, Any]] = {}
        for s_name, data in self.methurator_data.items():
            general_stats_data[s_name] = {
                "minimum_coverage": data.get("minimum_coverage"),
                "total_cpgs": data.get("total_cpgs"),
                "total_reads": data.get("total_reads"),
                "asymptote": data.get("asymptote"),
                "saturation_pct": data.get("saturation_pct"),
            }

        headers = {
            "minimum_coverage": {
                "title": "Minimum coverage",
                "description": "Minimum CpGs coverage",
                "format": "{:,.0f}",
                "scale": "Greens",
                "hidden": True,
            },
            "total_cpgs": {
                "title": "CpGs",
                "description": "Total number of observed CpGs at full sequencing depth (t=1)",
                "format": "{:,.0f}",
                "scale": "Blues",
            },
            "total_reads": {
                "title": "Reads",
                "description": "Total number of reads in the BAM file",
                "format": "{:,.0f}",
                "scale": "Purples",
                "hidden": True,
            },
            "asymptote": {
                "title": "Asymptote",
                "description": "Theoretical maximum number of CpGs at t = 1000",
                "format": "{:,.0f}",
                "scale": "BuPu",
            },
            "saturation_pct": {
                "title": "Saturation",
                "description": "CpG sequencing saturation (percentage of theoretical maximum CpGs detected)",
                "suffix": "%",
                "max": 100,
                "min": 0,
                "scale": "RdYlGn",
            },
        }

        self.general_stats_addcols(general_stats_data, headers)

    def _add_saturation_plot(self):
        """Add the CpG saturation curve plot showing CpGs vs t-values for GT estimator format.

        GT data points are: [t, saturation, total_cpgs, ci_low, ci_high]
        """
        # Collect plot data for each sample, one dataset per minimum coverage level
        plot_data_by_coverage: dict[int, dict[str, dict[float, float]]] = {}

        for s_name, data in self.methurator_data.items():
            saturation_analysis = data.get("saturation_analysis", {})

            for min_cov, sat_data in saturation_analysis.items():
                if min_cov not in plot_data_by_coverage:
                    plot_data_by_coverage[min_cov] = {}

                # Extract GT data points: [t, saturation, total_cpgs, ci_low, ci_high]
                sat_points = sat_data.get("data", [])
                sample_curve: dict[float, float] = {}
                for point in sat_points:
                    if len(point) >= 3:
                        t_val = point[0]  # t-value as x-axis
                        cpgs = point[2]  # total_cpgs as y-axis
                        sample_curve[float(t_val)] = float(cpgs)

                if sample_curve:
                    plot_data_by_coverage[min_cov][s_name] = sample_curve

        # Filter out coverage levels with no valid data and sort
        coverage_levels = sorted([cov for cov, data in plot_data_by_coverage.items() if data])

        if not coverage_levels:
            self.add_section(
                name="CpG Saturation Curve",
                anchor="methurator_saturation",
                description="Saturation curves showing the number of CpG sites detected at each sequencing depth.",
                content=_make_alert(
                    "No CpG saturation data available. "
                    "No valid saturation analysis data was found for any coverage level."
                ),
            )
            return

        # Build datasets and labels (works for single or multiple coverage levels)
        datasets = [plot_data_by_coverage[cov] for cov in coverage_levels]
        data_labels = [
            {
                "name": f"Min Coverage {cov}x",
                "ylab": "Number of CpGs",
                "title": f"Methurator: CpG Saturation Curve (min. coverage {cov}x)",
            }
            for cov in coverage_levels
        ]

        pconfig = LinePlotConfig(
            id="methurator_saturation_plot",
            title=f"Methurator: CpG Saturation Curve (min. coverage {coverage_levels[0]}x)",
            xlab="Extrapolation factor (t = 1 means observed sequencing depth)",
            ylab="Number of CpGs",
            xmin=0,
            ymin=0,
            tt_label="t = <b>{point.x:.2f}</b>: {point.y:,.0f} CpGs",
            data_labels=data_labels,
        )

        self.add_section(
            name="CpG Saturation Curve",
            anchor="methurator_saturation",
            description="Saturation curves showing the number of CpG sites detected at each sequencing depth.",
            helptext="A flattening curve indicates saturation, where additional sequencing yields diminishing returns. t=1.0 represents the actual sequencing depth.",
            plot=linegraph.plot(datasets, pconfig),
        )
